import { expect, test, type Page, type TestInfo } from '@playwright/test';

async function openFlow(page: Page, id: string, info: TestInfo) {
  const presentation = info.project.name.includes('narrow') ? '?theme=dark' : '';
  await page.goto(`/${presentation}#flows/${id}`);
  const preview = page.locator('.reference-preview');
  await expect(preview).toBeVisible();
  return preview;
}

